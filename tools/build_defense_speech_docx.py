def add_paragraph(document: Document, text: str, size: int = 12, bold: bool = False) -> None:
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    run = paragraph.add_run(text)
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.bold = bold


def main() -> None:
    document = Document()

    styles = document.styles
    styles["Normal"].font.name = "Times New Roman"
    styles["Normal"].font.size = Pt(12)

    title = document.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run("Речь к презентации дипломной работы")
    run.bold = True
    run.font.name = "Times New Roman"
    run.font.size = Pt(16)

    subtitle = document.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run("TuristPRO — система бронирования экскурсий и мастер-классов")
    run.font.name = "Times New Roman"
    run.font.size = Pt(12)

    document.add_paragraph()

    for heading, text in SPEECH:
        add_paragraph(document, heading, size=12, bold=True)
        add_paragraph(document, text, size=12)

    document.add_paragraph()
    note = document.add_paragraph()
    note.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = note.add_run("Ориентировочная длительность выступления: 5–7 минут.")
    run.italic = True
    run.font.name = "Times New Roman"
    run.font.size = Pt(12)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    document.save(OUT)
    print(OUT)


if __name__ == "__main__":
    main()
